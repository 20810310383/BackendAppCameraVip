const PACK_COLORS = ['#FF70A6', '#F7B955', '#6C8CFF', '#65C9A4', '#AF76E8', '#FF855C'];

function toPosixPath(value) {
  return value.split(path.sep).join('/');
}

function humanizePackName(packName) {
  return packName
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/(\D)(\d+)/g, '$1 $2')
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function colorForPack(packName) {
  const hash = [...packName].reduce((value, character) => value + character.charCodeAt(0), 0);
  return PACK_COLORS[hash % PACK_COLORS.length];
}

async function collectStickerFiles(directory, relativeDirectory = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const sourcePath = path.join(directory, entry.name);
    const relativePath = relativeDirectory ? path.join(relativeDirectory, entry.name) : entry.name;

    if (entry.isDirectory()) {
      files.push(...await collectStickerFiles(sourcePath, relativePath));
      continue;
    }
    if (!entry.isFile() || !/\.webp$/i.test(entry.name)) continue;

    const fileInfo = await stat(sourcePath);
    files.push({
      sourcePath,
      relativePath: toPosixPath(relativePath),
      fileName: entry.name,
      sizeBytes: fileInfo.size,
    });
  }

  return files;
}

function createManifest(packMap) {
  const packs = [...packMap.values()]
    .sort((left, right) => left.label.localeCompare(right.label))
    .map((pack) => ({
      ...pack,
      stickers: pack.stickers.sort((left, right) => left.fileName.localeCompare(right.fileName)),
    }));

  return [
    '/**',
    ' * Generated by Backend/scripts/generate-sticker-previews.mjs.',
    ' * Do not edit manually; run npm run sync:stickers after adding a sticker folder.',
    ' */',
    "import type { StickerAssetPack } from './sticker-assets';",
    '',
    'export const GENERATED_STICKER_ASSET_PACKS: StickerAssetPack[] = ' + JSON.stringify(packs, null, 2) + ';',
    '',
  ].join('\n');
}

const files = await collectStickerFiles(stickerRoot);
const packMap = new Map();
let generated = 0;

for (const [index, file] of files.entries()) {
  const packId = path.posix.dirname(file.relativePath);
  // Root sticker-new files already belong to the curated Hot Trend pack.
  // Folders below it are automatically registered as separate sticker packs.
  if (!packId.includes('/')) continue;

  const metadata = await sharp(file.sourcePath, { animated: true }).metadata();
  if (!manifestOnly) {
    const destinationPath = path.join(previewRoot, ...file.relativePath.split('/'));
    await mkdir(path.dirname(destinationPath), { recursive: true });
    await sharp(file.sourcePath, { animated: false })
      .resize({
        width: 120,
        height: 120,
        fit: 'contain',
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .webp({ quality: 62, effort: 4 })
      .toFile(destinationPath);
    generated += 1;
    console.log('✓ [' + (index + 1) + '/' + files.length + '] Preview: ' + file.relativePath);
  }

  const packName = path.posix.basename(packId);
  const displayName = PACK_LABELS[packName] || humanizePackName(packName);
  let pack = packMap.get(packId);
  if (!pack) {
    pack = {
      id: packId,
      emoji: PACK_EMOJIS[packName] || '✨',
      label: displayName,
      color: colorForPack(packName),
      stickers: [],
    };
    packMap.set(packId, pack);
  }

  const stickerNumber = pack.stickers.length + 1;
  pack.stickers.push({
    id: packId.replace(/\//g, '-') + '-' + stickerNumber,
    packId,
    fileName: file.fileName,
    sizeBytes: file.sizeBytes,
    label: displayName + ' ' + stickerNumber,
    searchTerms: [packName, displayName.toLowerCase(), 'sticker'],
    isAnimated: (metadata.pages || 1) > 1,
  });

}

await mkdir(path.dirname(manifestPath), { recursive: true });
await writeFile(manifestPath, createManifest(packMap), 'utf8');
if (!manifestOnly) console.log('Generated ' + generated + ' sticker previews in ' + previewRoot);
console.log('Registered ' + packMap.size + ' sticker pack(s) in ' + manifestPath);
